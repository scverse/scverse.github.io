#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["tinycss2>=1.4"]
# ///
"""Merge the light and dark modes of a Chroma style into one stylesheet using light-dark().

The style is `markup.highlight.style` from config.toml; Hugo finds its counterpart in the other mode
(see https://gohugo.io/quick-reference/syntax-highlighting-styles/#modes).
light-dark() only takes colors, so other properties (font-weight, font-style, …) come from the light mode.

Writes assets/chroma.css, formatted like Biome would, since this runs as a prek hook before Biome.
"""

import subprocess
import sys
import tomllib
from pathlib import Path

import tinycss2

ROOT = Path(__file__).parent.parent
OUT = ROOT / "assets/chroma.css"
# what a color property falls back to in the theme that doesn’t set it
FALLBACK = {"color": "currentcolor", "background-color": "transparent"}

type Rules = dict[str, dict[str, str]]


def chroma_rules(style: str, mode: str) -> Rules:
    css = subprocess.run(
        ["hugo", "gen", "chromastyles", f"--style={style}", f"--mode={mode}"],
        check=True,
        capture_output=True,
        text=True,
        cwd=ROOT,
    ).stdout
    rules: Rules = {}
    for rule in tinycss2.parse_stylesheet(css, skip_comments=True, skip_whitespace=True):
        if rule.type != "qualified-rule":
            continue
        selector = tinycss2.serialize(rule.prelude).strip()
        decls = tinycss2.parse_blocks_contents(rule.content, skip_comments=True, skip_whitespace=True)
        rules[selector] = {
            d.lower_name: tinycss2.serialize(d.value).strip()
            for d in decls
            if d.type == "declaration"
        }
    return rules


def merge(light: Rules, dark: Rules) -> Rules:
    merged: Rules = {}
    for selector in light | dark:  # light’s order first, then dark-only selectors
        l, d = light.get(selector, {}), dark.get(selector, {})
        props = merged[selector] = {}
        for prop in l | d:
            if prop in FALLBACK:
                lv, dv = l.get(prop, FALLBACK[prop]), d.get(prop, FALLBACK[prop])
                props[prop] = lv if lv == dv else f"light-dark({lv}, {dv})"
            elif prop in l:
                props[prop] = l[prop]
    return merged


def main() -> None:
    config = tomllib.loads((ROOT / "config.toml").read_text())
    style = config["markup"]["highlight"]["style"]
    rules = merge(chroma_rules(style, "light"), chroma_rules(style, "dark"))
    lines = [f"/* Generated by scripts/highlight_styles.py from the light and dark modes of {style} */"]
    for selector, props in rules.items():
        if props:
            lines += [f"{selector} {{", *(f"    {k}: {v};" for k, v in props.items()), "}"]
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as e:
        sys.exit(e.stderr)
